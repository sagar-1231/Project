create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  name text not null, whatsapp text default '', hours text default '', address text default ''
);
create table if not exists public.menu (
  id bigint generated by default as identity primary key,
  name text not null, cat text not null default 'Anya', price numeric not null,
  half numeric, type text not null default 'veg', descr text default '', avail boolean not null default true
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  no text, ts bigint not null, name text, phone text, type text, addr text, note text,
  items jsonb, total numeric, status text not null default 'new'
);
alter table public.settings enable row level security;
alter table public.menu enable row level security;
alter table public.orders enable row level security;

drop policy if exists "read settings" on public.settings; drop policy if exists "admin settings" on public.settings;
drop policy if exists "read menu" on public.menu;         drop policy if exists "admin menu" on public.menu;
drop policy if exists "admin orders" on public.orders;
create policy "read settings" on public.settings for select using (true);
create policy "read menu" on public.menu for select using (true);
create policy "admin settings" on public.settings for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin menu" on public.menu for all to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "admin orders" on public.orders for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Customer seedha orders table mein nahi likh sakta. Order is function se jata hai, jo daam server ke menu se lagata hai.
create or replace function public.place_order(p_name text, p_phone text, p_type text, p_addr text, p_note text, p_items jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare it jsonb; m public.menu%rowtype; q int; sz text; pr numeric; tot numeric := 0; outi jsonb := '[]'; oid bigint; onum text; nm text; ty text := p_type;
begin
  if coalesce(p_phone,'') !~ '^[6-9][0-9]{9}$' then raise exception 'Sahi 10 digit mobile number chahiye.'; end if;
  if coalesce(trim(p_name),'') = '' then raise exception 'Apna naam likhein.'; end if;
  if ty is distinct from 'delivery' then ty := 'takeaway'; end if;
  if ty = 'delivery' and length(coalesce(p_addr,'')) < 8 then raise exception 'Delivery ka poora pata likhein.'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 40 then raise exception 'Cart khaali hai.'; end if;
  for it in select value from jsonb_array_elements(p_items) loop
    select * into m from public.menu where id = (it->>'id')::bigint;
    if not found then raise exception 'Menu badal gaya hai. Page dobara kholein.'; end if;
    if not m.avail then raise exception '% abhi available nahi hai.', m.name; end if;
    q := least(50, greatest(1, coalesce((it->>'qty')::int, 1)));
    sz := case when it->>'size' = 'h' then 'h' else 'f' end;
    if sz = 'h' and m.half is null then raise exception '% mein half nahi hai. Page dobara kholein.', m.name; end if;
    pr := case when sz = 'h' then m.half else m.price end;
    nm := m.name || case when m.half is not null then case when sz = 'h' then ' (Half)' else ' (Full)' end else '' end;
    tot := tot + q * pr;
    outi := outi || jsonb_build_array(jsonb_build_object('id', m.id, 'name', nm, 'size', sz, 'qty', q, 'price', pr));
  end loop;
  insert into public.orders(ts, name, phone, type, addr, note, items, total)
  values ((extract(epoch from now()) * 1000)::bigint, left(trim(p_name), 60), p_phone, ty,
          case when ty = 'delivery' then left(p_addr, 300) else '' end, left(coalesce(p_note,''), 200), outi, tot)
  returning id into oid;
  onum := 'AK-' || lpad(oid::text, 4, '0');
  update public.orders set no = onum where id = oid;
  return jsonb_build_object('no', onum, 'total', tot, 'items', outi);
end $$;
revoke all on function public.place_order(text,text,text,text,text,jsonb) from public;
grant execute on function public.place_order(text,text,text,text,text,jsonb) to anon, authenticated;


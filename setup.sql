create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  name text not null, whatsapp text default '', hours text default '', address text default ''
);
create table if not exists public.menu (
  id bigint generated by default as identity primary key,
  name text not null, cat text not null default 'Anya', price numeric not null,
  half numeric, type text not null default 'veg', descr text default '', avail boolean not null default true
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  no text, ts bigint not null, name text, phone text, type text, addr text, note text,
  items jsonb, total numeric, status text not null default 'new'
);
